import assert from 'node:assert/strict';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
const slug=process.argv[2];
assert.match(slug??'',/^[a-z0-9]+(?:-[a-z0-9]+)*$/);
const term=JSON.parse(readFileSync('content/glossary.json','utf8')).find(row=>row.slug===slug);
assert.ok(term?.status==='reviewed' && term.reviewer && term.updated,'Wymagana ręczna akceptacja, podpis i rzeczywista data aktualizacji.');
assert.match(term.updated,/^\d{4}-\d{2}-\d{2}$/);
const dir=`app/slownik-psychologiczny/${slug}`;
mkdirSync(dir,{recursive:true});
writeFileSync(`${dir}/page.tsx`,`import GlossaryEntryPage, {glossaryMetadata} from '../../../components/GlossaryEntryPage';\nexport const metadata=glossaryMetadata('${slug}');\nexport default function Page(){return <GlossaryEntryPage slug="${slug}"/>;}\n`,{flag:'wx'});
