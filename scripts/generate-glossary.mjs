import {readdirSync,readFileSync,mkdirSync,unlinkSync,rmdirSync,writeFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {readRegistry} from './glossary-registry.mjs';
import {isPublishedTerm} from '../lib/glossary-policy.mjs';
const root=fileURLToPath(new URL('../app/slownik-psychologiczny/',import.meta.url));
const marker='// Generated by scripts/generate-glossary.mjs\n';
const approved=new Set(readRegistry().filter(isPublishedTerm).map(x=>x.slug));
for(const dir of readdirSync(root,{withFileTypes:true}).filter(x=>x.isDirectory())){
 const path=`${root}${dir.name}/page.tsx`;
 if(!existsSync(path)||!readFileSync(path,'utf8').startsWith(marker))continue;
 if(!approved.has(dir.name)){unlinkSync(path);if(!readdirSync(`${root}${dir.name}`).length)rmdirSync(`${root}${dir.name}`);}
}
for(const slug of approved){
 const dir=`${root}${slug}`,path=`${dir}/page.tsx`;
 if(existsSync(path)&&!readFileSync(path,'utf8').startsWith(marker))throw new Error(`Refusing to overwrite manual route: ${slug}`);
 mkdirSync(dir,{recursive:true});
 writeFileSync(path,`${marker}import GlossaryEntryPage,{glossaryMetadata} from '../../../components/GlossaryEntryPage';\nexport const metadata=glossaryMetadata('${slug}');\nexport default function Page(){return <GlossaryEntryPage slug="${slug}"/>;}\n`);
}
console.log(`Trasy słownika: ${approved.size} zatwierdzonych.`);
